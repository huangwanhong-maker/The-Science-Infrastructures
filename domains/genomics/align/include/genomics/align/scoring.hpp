// The names of the protein matrices matrix() knows.
inline std::vector<std::string> matrix_names() {
  std::vector<std::string> names;
  for (const auto& m : detail::matrices::ALL) names.emplace_back(m.name);
  return names;
}

// A named protein matrix on the 24 protein codes ("BLOSUM62", "PAM250", "BLOSUM80-BLAST", ...;
// case as NCBI writes it). Throws std::invalid_argument for a name it does not know.
inline Matrix matrix(std::string_view name) {
  for (const auto& m : detail::matrices::ALL)
    if (m.name == name) {
      Matrix x;
      x.name = std::string(name);
      x.size = 24;
      x.score.assign(m.score, m.score + 576);
      return x;
    }
  throw std::invalid_argument("genomics::align::matrix: no matrix named " + std::string(name));
}

