// Scoring schemes: the named substitution matrices of NCBI, the DNA scorings of the common
// aligners, and the background amino-acid frequencies of Robinson and Robinson.
//
// - Protein matrices, transcribed exactly from NCBI's files (https://ftp.ncbi.nih.gov/blast/
//   matrices/, retrieved 2026-10-24; the SHA-256 of each file in the module's README), in the
//   order of their rows and columns, ARNDCQEGHILKMFPSTWYVBZX*, which is the protein code order
//   of sequence/alphabet.hpp, so that a code indexes the matrix directly:
//     BLOSUM45, BLOSUM50, BLOSUM80   in 1/3-bit units;  BLOSUM62, BLOSUM90 in 1/2-bit units
//                                    (Henikoff and Henikoff 1992, PNAS 89, 10915–10919);
//     PAM30, PAM70                   scale ln 2 / 2;  PAM250 scale ln 2 / 3 (Dayhoff, Schwartz
//                                    and Orcutt 1978, Atlas of Protein Sequence and Structure 5,
//                                    suppl. 3, 345–352; the files made by Altschul's "pam" 1.0.6).
//   The files' own headers give the relative entropy and expected score of each (BLOSUM62:
//   0.6979 bits and −0.5209). The check holds every matrix symmetric and verifies entries and
//   these published figures against the files.
// - BLOSUM80-BLAST: the BLOSUM80 built into NCBI BLAST (s_Blosum80PSM of sm_blosum80.c in the NCBI
//   C++ Toolkit's util/tables, retrieved 2026-10-24), at the scale ln 2 / 2, where the FTP file is
//   at ln 2 / 3: the two differ in 324 of the 400 entries of the twenty standard residues, and
//   BLAST's tables of λ, K and H for "BLOSUM80" (statistics.hpp) belong to this one. For the
//   other seven the built-in matrices of BLAST equal the FTP files on the twenty residues and
//   differ only in the rows of B, Z and X.
// - DNA scorings: match and mismatch on A, C, G, T, N against anything −1, and affine gaps
//   (a gap of length L costs open + L · extend, types.hpp), as the aligners set them by default:
//     blastn        2, −3, open 5, extend 2   (BLAST+ blastn task; Camacho et al. 2009, BMC
//                                             Bioinformatics 10, 421; the BLAST+ manual, table C2)
//     bwa_mem       1, −4, open 6, extend 1   (Li 2013, arXiv:1303.3997, bwa mem -A1 -B4 -O6 -E1)
//     minimap2_*    the first piece of minimap2's two-piece affine gap (Li 2018, Bioinformatics
//                   34, 3094–3100; the manual's presets): map-ont 2, −4, 4, 2; map-hifi 1, −4,
//                   6, 2; sr 2, −8, 12, 2; asm5 1, −19, 39, 3.
// - blastp(): BLOSUM62 with open 11, extend 1, the default of BLAST+ blastp.
// - Background frequencies of the twenty amino acids (Robinson and Robinson 1991, PNAS 88,
//   8880–8884), as NCBI BLAST tabulates them (Robinson_prob in blast_stat.c of the NCBI C++
//   Toolkit, retrieved 2026-10-24), normalised to sum 1, in the code order; B, Z, X and * have
//   frequency 0.

